// Helper to reliably find any product by ID (number or string)
export function getProductById(id: string | number): Product {
  const numId = typeof id === "number" ? id : parseInt(id, 10);

  // 1. Check allProductsData
  let found = allProductsData.find((p) => p.id === numId || String(p.id) === String(id));
  if (found) return found;

  // 2. Check jewelryProductsData
  found = jewelryProductsData.find((p) => p.id === numId || String(p.id) === String(id));
  if (found) return found;

  // 3. Check CATEGORY_PRODUCTS
  const catProduct = CATEGORY_PRODUCTS.find((p) => p.id === numId || String(p.id) === String(id));
  if (catProduct) {
    return {
      id: catProduct.id,
      title: catProduct.title,
      seller: catProduct.seller,
      image: catProduct.image,
      secondaryImage: catProduct.secondaryImage,
      images: [catProduct.image, ...(catProduct.secondaryImage ? [catProduct.secondaryImage] : [])],
      rating: catProduct.rating,
      favorites: catProduct.favorites,
      price: catProduct.price,
      originalPrice: catProduct.originalPrice,
      isDiscounted: catProduct.isDiscounted,
      discountPercent: catProduct.discountPercent,
      isQuote: catProduct.isQuote,
      isFeatured: catProduct.isFeatured,
      category: catProduct.category,
      brand: catProduct.brand,
      sku: catProduct.sku || `SKU-${catProduct.id}`,
      status: catProduct.status || "In Stock",
      description:
        catProduct.description ||
        `${catProduct.title} - High quality authentic merchandise by ${catProduct.brand}.`,
      reviewsCount: 0,
      commentsCount: 0,
      viewsCount: 120,
    };
  }

  // Fallback to first product
  return allProductsData[0] || jewelryProductsData[0];
}
